"""Generate the theme-conditional skin XML from resources/themes.json.

Explicit authoring tool. ``--check`` only compares and never writes. It does
not rebuild other source, package, deploy, connect to Kodi or change user
preferences. The media-flag variables at the end of the theme include are not
theme data and are copied verbatim.

Selection rules:
  * ``Window(Home).Property(YoPlayer.Theme.Preview)`` (set only while the
    chooser has focus on a card) wins over the saved ``Skin.String``.
  * An empty saved value means the default theme (``themes.json`` "default").
  * ``aliases`` map retired ids to their replacement (``sand`` -> ``mist``).
  * Anything else, including ``classic``, falls back to the classic literals.
"""
import json
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SKIN = ROOT / 'source/skin.yoplayer.infuse'
THEME_XML = SKIN / '1080p/Includes_YoPlayer_Themes.xml'
INCLUDES_XML = SKIN / '1080p/Includes.xml'
TAIL_MARKER = '  <variable name="YoPlayerVideoFlagTexture">'
PREVIEW = 'Window(Home).Property(YoPlayer.Theme.Preview)'
SAVED = 'Skin.String(YoPlayerTheme)'
# Every window rendered by this skin participates. Artwork/video pixels do not.
SCOPE = 'true'
PLAYBACK_DIALOG = '[Window.IsActive(fullscreenvideo) | Window.IsActive(visualisation)]'
ROLE_VARIABLE = re.compile(r'<variable name="(YoPlayerTheme_(accentText|bg|line|secondary|text|untint)_[^"]+)">')
LAST_VALUE = re.compile(r'<value>([^<]*)</value>\s*</variable>')
DARK_CONTEXT = re.compile(r'  <expression name="YoPlayerDarkSelectContext">[^<]*</expression>\n')


def spec():
    return json.loads((SKIN / 'resources/themes.json').read_text(encoding='utf8'))


def argb(hex_colour):
    value = hex_colour.lstrip('#').upper()
    return 'FF' + value if len(value) == 6 else value[6:] + value[:6]


def equals(source, ident, aliases):
    names = [ident] + sorted(k for k, v in aliases.items() if v == ident)
    parts = ['String.IsEqual(%s,%s)' % (source, name) for name in names]
    return parts[0] if len(parts) == 1 else '[' + ' | '.join(parts) + ']'


def selected(ident, data):
    """Preview wins; an empty saved value is the default theme."""
    aliases = data.get('aliases', {})
    saved = equals(SAVED, ident, aliases)
    if ident == data['default']:
        saved = '[%s | String.IsEmpty(%s)]' % (saved, SAVED)
    return '[%s | [String.IsEmpty(%s) + %s]]' % (equals(PREVIEW, ident, aliases), PREVIEW, saved)


def saved_only(ident, data):
    saved = equals(SAVED, ident, data.get('aliases', {}))
    if ident == data['default']:
        saved = '[%s | String.IsEmpty(%s)]' % (saved, SAVED)
    return saved


def role_value(role, classic_literal, theme):
    if role == 'untint':
        opaque = re.fullmatch(r'FF[0-9A-Fa-f]{6}', classic_literal)
        return 'FFFFFFFF' if opaque else classic_literal
    return argb(theme[role])


def variable(name, values, fallback):
    lines = ['  <variable name="%s">' % name]
    lines += ['    <value condition="%s">%s</value>' % (c, v) for c, v in values]
    lines += ['    <value>%s</value>' % fallback, '  </variable>']
    return lines


def themed(data):
    return [t for t in data['themes'] if t['id'] != 'classic']


def render(current_text, data):
    classic = data['themes'][0]
    assert classic['id'] == 'classic', 'classic must stay first: the asset builder skips index 0'
    if TAIL_MARKER not in current_text:
        raise ValueError('Theme include tail marker missing')
    tail = current_text[current_text.index(TAIL_MARKER):]
    roles = [(m.group(1), m.group(2), LAST_VALUE.search(current_text, m.end()).group(1))
             for m in ROLE_VARIABLE.finditer(current_text)]
    if not roles:
        raise ValueError('No role variables found')
    themes = themed(data)
    out = ["<?xml version='1.0' encoding='utf-8'?>", '<includes>',
           '  <!-- Generated by tools/build_theme_xml.py from resources/themes.json; edit the JSON, not this block. -->',
           '  <expression name="YoPlayerThemeScope">%s</expression>' % SCOPE]
    for t in themes:
        out.append('  <expression name="YoPlayerThemeIs_%s">%s</expression>' % (t['id'], selected(t['id'], data)))
        out.append('  <expression name="YoPlayerThemeScoped_%s">%s + %s</expression>' % (t['id'], SCOPE, selected(t['id'], data)))

    def scoped(build, fallback):
        return [('$EXP[YoPlayerThemeScoped_%s]' % t['id'], build(t)) for t in themes], fallback

    for name, role, literal in roles:
        values, fallback = scoped(lambda t: role_value(role, literal, t), literal)
        out += variable(name, values, fallback)
    assets, fallback = scoped(lambda t: 'infuse/themes/%s/' % t['id'], 'infuse/')
    out += variable('YoPlayerThemeAssets', assets, fallback)
    # Hand-written before 142; now generated so every theme id lives in one place.
    values, _ = scoped(lambda t: argb(t['text']), None)
    out += variable('YoPlayerBrowseSelectedInk', values, 'FF006674')

    def unscoped(build):
        return [('$EXP[YoPlayerThemeIs_%s]' % t['id'], build(t)) for t in themes]

    logo = lambda t: 'infuse/brand/logo-white.png' if t['dark'] else 'infuse/brand/logo-light.png'
    out += variable('YoPlayerThemeLogo', unscoped(logo), 'infuse/brand/logo-light.png')
    out += variable('YoPlayerThemeOverlayLogo', unscoped(logo), 'infuse/brand/logo-white.png')
    # Chooser preview: the chooser sits over skin settings, outside the browse
    # scope, so these follow only the preview/saved selection.
    for role in ('bg', 'surface', 'hover', 'text', 'secondary', 'line', 'ring', 'progress'):
        out += variable('YoPlayerThemePreview_' + role, unscoped(lambda t: argb(t[role])), argb(classic[role]))
    out += ui_variables(data)
    out += variable('YoPlayerThemeName', [(saved_only(t['id'], data), t['name']) for t in themes], classic['name'])
    out += variable('YoPlayerThemePreviewName', unscoped(lambda t: t['name']), classic['name'])
    return '\n'.join(out) + '\n' + tail


def dark_context(data):
    # Expressions may not nest reliably on every target build, so the dark-theme
    # browse condition is inlined rather than referenced.
    browse = ' | '.join('[%s + %s]' % (SCOPE, selected(t['id'], data)) for t in themed(data) if t['dark'])
    assert browse
    return '  <expression name="YoPlayerDarkSelectContext">[%s | %s]</expression>\n' % (PLAYBACK_DIALOG, browse)


def ui_variables(data):
    """Semantic colours shared by every window and literal white alpha mask.

    Native texture filenames stay literal; only InfoColor is dynamic. This is
    supported by Kodi for all texture tags, including texturefocus/radio/slider.
    Playback uses one neutral transparent glass material in every theme.
    """
    palettes = {t['id']: t for t in data['themes']}
    roles = {'bg': 'bg', 'artveil': 'bg', 'surface': 'surface', 'text': 'text',
             'muted': 'secondary', 'disabled': 'secondary', 'line': 'line',
             'focus': 'ring', 'state': 'accentText', 'progress': 'progress'}
    glass = {'bg': 'A6191E24', 'artveil': '66191E24', 'surface': 'B3191E24',
             'text': 'FFF4F6F7', 'muted': 'FFBAC2CA', 'disabled': 'FF737B83',
             'line': '66FFFFFF', 'focus': 'FFFFFFFF', 'state': 'FFF4F6F7',
             'progress': 'FFF4F6F7', 'panel': 'FF191E24'}
    def colour(t, role, overlay=False):
        if overlay:
            return glass[role]
        material = t if t['dark'] else palettes['ink'] if overlay else t
        value = t['accentText'] if role == 'state' and overlay and t['dark'] else material[roles[role]]
        result = argb(value)
        if role == 'artveil':
            return ('66' if material['dark'] else 'D9') + result[2:]
        return 'F5' + result[2:] if overlay and role in ('surface', 'bg') else result
    result = []
    for role in roles:
        overlay_values = [('$EXP[YoPlayerThemeIs_' + t['id'] + ']', colour(t, role, True)) for t in themed(data)]
        result += variable('YoPlayerOverlay_' + role, overlay_values, colour(palettes['classic'], role, True))
        values = [(PLAYBACK_DIALOG, '$VAR[YoPlayerOverlay_' + role + ']')]
        values += [('$EXP[YoPlayerThemeIs_' + t['id'] + ']', colour(t, role)) for t in themed(data)]
        result += variable('YoPlayerUi_' + role, values, colour(palettes['classic'], role))
    variants = set()
    for path in (SKIN / '1080p').glob('*.xml'):
        if path.name == THEME_XML.name:
            continue
        variants.update(re.findall(r'\$VAR\[YoPlayer(Ui|Overlay)_([a-z]+)_([0-9A-F]{2})\]', path.read_text(encoding='utf-8')))
    for family, role, alpha in sorted(variants):
        overlay = family == 'Overlay'
        def value(t):
            raw = colour(t, role, overlay)
            opacity = int(raw[:2], 16) * int(alpha, 16) // 255
            return '%02X' % opacity + raw[2:]
        values = [] if overlay else [(PLAYBACK_DIALOG, '$VAR[YoPlayerOverlay_' + role + '_' + alpha + ']')]
        values += [('$EXP[YoPlayerThemeIs_' + t['id'] + ']', value(t)) for t in themed(data)]
        result += variable('YoPlayer' + family + '_' + role + '_' + alpha, values, value(palettes['classic']))
    # Every Ui alpha variant can fall back to its matching overlay variant.
    for _, role, alpha in sorted(v for v in variants if v[0] == 'Ui' and ('Overlay', v[1], v[2]) not in variants):
        def value(t):
            raw = colour(t, role, True)
            return '%02X' % (int(raw[:2], 16) * int(alpha, 16) // 255) + raw[2:]
        result += variable('YoPlayerOverlay_' + role + '_' + alpha,
                           [('$EXP[YoPlayerThemeIs_' + t['id'] + ']', value(t)) for t in themed(data)],
                           value(palettes['classic']))
    result += variable('YoPlayerOverlay_panel', [], glass['panel'])
    return result


CHOOSER_XML = SKIN / '1080p/custom_1187_ThemeColors.xml'
FIRST_ROW = 6201
RESET_ID, CANCEL_ID = 6210, 6211


def chooser_order(data):
    """Default first, classic last: 6201.. in this order."""
    rest = [t for t in themed(data) if t['id'] != data['default']]
    return [t for t in themed(data) if t['id'] == data['default']] + rest + [data['themes'][0]]


def saved_condition(theme, data):
    if theme['id'] != 'classic':
        return saved_only(theme['id'], data)
    return '![%s]' % ' | '.join(saved_only(t['id'], data) for t in themed(data))


def image(left, top, width, height, texture, diffuse=None, border=None, visible=None, aspect=None):
    attrs = ''.join(' %s="%s"' % (k, v) for k, v in (('border', border), ('colordiffuse', diffuse)) if v)
    lines = ['    <control type="image">',
             '      <left>%d</left>' % left, '      <top>%d</top>' % top,
             '      <width>%d</width>' % width, '      <height>%d</height>' % height,
             '      <texture%s>%s</texture>' % (attrs, texture)]
    if aspect:
        lines.append('      <aspectratio>%s</aspectratio>' % aspect)
    if visible:
        lines.append('      <visible>%s</visible>' % visible)
    return lines + ['    </control>']


def label(left, top, width, height, text, font, colour, align='left', visible=None):
    lines = ['    <control type="label">',
             '      <left>%d</left>' % left, '      <top>%d</top>' % top,
             '      <width>%d</width>' % width, '      <height>%d</height>' % height,
             '      <label>%s</label>' % text, '      <font>%s</font>' % font,
             '      <textcolor>%s</textcolor>' % colour,
             '      <align>%s</align>' % align, '      <aligny>center</aligny>']
    if visible:
        lines.append('      <visible>%s</visible>' % visible)
    return lines + ['    </control>']


def button(ident, left, top, width, height, nav, focus, clicks, text=None):
    lines = ['    <control type="button" id="%d">' % ident,
             '      <left>%d</left>' % left, '      <top>%d</top>' % top,
             '      <width>%d</width>' % width, '      <height>%d</height>' % height]
    if text:
        lines += ['      <label>%s</label>' % text, '      <font>infuse_meta</font>',
                  '      <textcolor>$VAR[YoPlayerThemePreview_text]</textcolor>',
                  '      <focusedcolor>$VAR[YoPlayerThemePreview_text]</focusedcolor>',
                  '      <align>center</align>', '      <aligny>center</aligny>', '      <textoffsetx>0</textoffsetx>']
    else:
        lines.append('      <label />')
    lines += ['      <texturefocus>-</texturefocus>', '      <texturenofocus>-</texturenofocus>']
    lines += ['      <%s>%d</%s>' % (k, v, k) for k, v in nav]
    lines += ['      <onback>Dialog.Close(1187)</onback>', '      <onfocus>%s</onfocus>' % focus]
    lines += ['      <onclick>%s</onclick>' % c for c in clicks]
    return lines + ['    </control>']


def chooser(data):
    """Theme chooser: list on the left, live preview on the right (UI3).

    The chooser opens over skin settings, outside the browse scope, so every
    colour here uses the unscoped YoPlayerThemePreview_* variables and the
    whole page follows the focused card.
    """
    order = chooser_order(data)
    ids = {t['id']: FIRST_ROW + i for i, t in enumerate(order)}
    last = FIRST_ROW + len(order) - 1
    p = lambda role: '$VAR[YoPlayerThemePreview_%s]' % role
    out = ["<?xml version='1.0' encoding='utf-8'?>",
           '<!-- Generated by tools/build_theme_xml.py from resources/themes.json. -->',
           '<window type="dialog" id="1187">',
           '  <defaultcontrol>%d</defaultcontrol>' % FIRST_ROW,
           '  <onload>ClearProperty(YoPlayer.Theme.Preview,home)</onload>']
    for t in order[1:]:
        out.append('  <onload condition="%s">SetFocus(%d)</onload>' % (saved_condition(t, data), ids[t['id']]))
    out += ['  <onunload>ClearProperty(YoPlayer.Theme.Preview,home)</onunload>', '  <controls>']
    out += image(0, 0, 1920, 1080, 'colors/white.png', p('bg'))
    out += image(90, 44, 290, 94, '$VAR[YoPlayerThemeLogo]', aspect='keep')
    out += label(90, 168, 600, 64, '主题配色', 'infuse_page_title', p('text'))
    out += label(90, 236, 600, 40, '上下选择即时预览 · 确定保存 · 返回取消', 'infuse_meta', p('secondary'))
    row_h, gap, top0, left, width = 108, 16, 304, 90, 570
    for i, t in enumerate(order):
        top = top0 + i*(row_h+gap)
        ident = ids[t['id']]
        out += image(left, top, width, row_h, 'infuse/home/white.png', p('surface'), border='16',
                     visible='!Control.HasFocus(%d)' % ident)
        out += image(left, top, width, row_h, 'infuse/home/white.png', p('hover'), border='16',
                     visible='Control.HasFocus(%d)' % ident)
        out += image(left-6, top-6, width+12, row_h+12, 'infuse/home/focus-ring.png', p('ring'), border='32',
                     visible='Control.HasFocus(%d)' % ident)
        out += image(left+14, top+12, 150, 84, 'infuse/themes/%s/preview.png' % t['id'], aspect='keep')
        out += label(left+186, top+14, 270, 44, t['name'], 'infuse_card_title', p('text'))
        out += label(left+186, top+58, 370, 36, t['context'], 'infuse_card_sub', p('secondary'))
        out += label(left+430, top+14, 120, 44, '使用中', 'infuse_card_sub', p('text'), align='right',
                     visible=saved_condition(t, data))
        clicks = ['Skin.SetString(YoPlayerTheme,%s)' % t['id'],
                  'ClearProperty(YoPlayer.Theme.Preview,home)', 'Dialog.Close(1187)']
        nav = [('onup', ident-1 if ident > FIRST_ROW else CANCEL_ID),
               ('ondown', ident+1 if ident < last else RESET_ID),
               ('onleft', ident), ('onright', ident)]
        out += button(ident, left, top, width, row_h, nav,
                      'SetProperty(YoPlayer.Theme.Preview,%s,home)' % t['id'], clicks)
    btn_top = top0 + len(order)*(row_h+gap) + 12
    default_name = next(t['name'] for t in order if t['id'] == data['default'])
    for ident, x, text, focus, first in (
            (RESET_ID, 90, '恢复默认（%s）' % default_name, data['default'], 'Skin.Reset(YoPlayerTheme)'),
            (CANCEL_ID, 390, '取消', None, None)):
        out += image(x, btn_top, 270, 64, 'infuse/home/white.png', p('surface'), border='16',
                     visible='!Control.HasFocus(%d)' % ident)
        out += image(x, btn_top, 270, 64, 'infuse/home/white.png', p('hover'), border='16',
                     visible='Control.HasFocus(%d)' % ident)
        out += image(x-6, btn_top-6, 282, 76, 'infuse/home/focus-ring.png', p('ring'), border='32',
                     visible='Control.HasFocus(%d)' % ident)
        other = CANCEL_ID if ident == RESET_ID else RESET_ID
        nav = [('onup', last), ('ondown', FIRST_ROW), ('onleft', other), ('onright', other)]
        if first:
            clicks = [first, 'ClearProperty(YoPlayer.Theme.Preview,home)', 'Dialog.Close(1187)']
            on_focus = 'SetProperty(YoPlayer.Theme.Preview,%s,home)' % focus
        else:
            clicks = ['Dialog.Close(1187)']
            on_focus = 'ClearProperty(YoPlayer.Theme.Preview,home)'
        out += button(ident, x, btn_top, 270, 64, nav, on_focus, clicks, text)
    # Live preview: a scaled home screen drawn only from interface roles.
    fx, fy, fw, fh = 730, 170, 1100, 620
    out += image(fx-2, fy-2, fw+4, fh+4, 'infuse/home/focus-ring.png', p('line'), border='32')
    out += image(fx+40, fy+28, 170, 56, '$VAR[YoPlayerThemeLogo]', aspect='keep')
    for i in range(4):
        out += image(fx+fw-40-48-i*64, fy+32, 48, 48, 'infuse/visual47/pill-white-62.png', p('surface'))
    out += label(fx+40, fy+108, 400, 40, '继续观看', 'infuse_card_title', p('text'))
    cw, ch = 320, 180
    for i in range(3):
        cx, cy = fx+40+i*(cw+30), fy+156
        # Stand-in for poster art: progress sits over artwork on the real home screen.
        out += image(cx, cy, cw, ch, 'infuse/home/white.png', 'FF6E6E73', border='16')
        if i == 0:
            out += image(cx-8, cy-8, cw+16, ch+16, 'infuse/home/focus-ring.png', p('ring'), border='32')
        if i < 2:
            out += image(cx+16, cy+ch-22, cw-32, 8, 'infuse/home/white.png', p('line'), border='4')
            out += image(cx+16, cy+ch-22, (cw-32)*(60-i*25)//100, 8, 'infuse/home/white.png', p('progress'), border='4')
        out += label(cx, cy+ch+10, cw, 36, '示例影片', 'infuse_card_title', p('text'), align='center')
        out += label(cx, cy+ch+46, cw, 30, '第1季 · 第%d集' % (i+3), 'infuse_card_sub', p('secondary'), align='center')
    out += label(fx+40, fy+446, 400, 40, '媒体分库', 'infuse_card_title', p('text'))
    for i in range(4):
        out += image(fx+40+i*256, fy+494, 236, 96, 'infuse/home/white.png', p('surface'), border='16')
    out += label(fx, 812, fw, 42, '已选用：$VAR[YoPlayerThemeName]    正在预览：$VAR[YoPlayerThemePreviewName]',
                 'infuse_meta', p('text'))
    out += label(fx, 860, fw, 36, '配色覆盖浏览、设置、详情、管理页和共享弹窗。', 'infuse_card_sub', p('secondary'))
    out += label(fx, 900, fw, 36, '播放面板使用对应的深色材质；海报、剧照和影片保持原色。', 'infuse_card_sub', p('secondary'))
    out += ['  </controls>', '</window>']
    return '\n'.join(out) + '\n'


def outputs():
    data = spec()
    theme_text = THEME_XML.read_text(encoding='utf-8')
    includes = INCLUDES_XML.read_text(encoding='utf-8')
    if len(DARK_CONTEXT.findall(includes)) != 1:
        raise ValueError('Expected exactly one YoPlayerDarkSelectContext expression')
    return {THEME_XML: render(theme_text, data),
            INCLUDES_XML: DARK_CONTEXT.sub(lambda _: dark_context(data), includes),
            CHOOSER_XML: chooser(data)}


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Compare generated XML without writing.')
    args = parser.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        if path.read_text(encoding='utf-8') != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not args.check:
                path.write_text(text, encoding='utf-8', newline='\n')
    if args.check:
        print(json.dumps({'status': 'stale' if stale else 'current', 'files': stale}))
        return 1 if stale else 0
    print(json.dumps({'written': stale}))
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
